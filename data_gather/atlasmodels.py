# Global SMOTE instance (if used, it does not need to be refitted per country)
smote = SMOTE(random_state=42)

def prepare_xy_with_transformers(country_data):
  # Instantiate transformers locally for each country to ensure independent fitting
  scalar = StandardScaler()
  imputer = SimpleImputer(strategy='constant', fill_value=0)
  selector = VarianceThreshold(threshold=0.01)

  # Keep 'Year' as a feature, drop only 'Country' and 'gdp_usd'
  x = country_data.drop(columns=['Country', 'gdp_usd'])
  y = country_data.gdp_usd

  # Identify categorical columns for Label Encoding (excluding 'Year' which is numeric)
  categorical_cols = x.select_dtypes(include=['object']).columns
  for col in categorical_cols:
    # Using a new LabelEncoder for each categorical column
    le = LabelEncoder()
    x[col] = le.fit_transform(x[col])

  # Impute missing values
  x_imputed = pd.DataFrame(imputer.fit_transform(x), columns=x.columns)

  # Feature Selection - Removing low variance features
  # Store column names before selection to map back correctly
  pre_selection_columns = x_imputed.columns
  x_selected_array = selector.fit_transform(x_imputed)

  # Get the names of features that were kept by the selector
  selected_feature_indices = selector.get_support(indices=True)
  selected_feature_names = pre_selection_columns[selected_feature_indices]
  x_selected = pd.DataFrame(x_selected_array, columns=selected_feature_names)

  # Check if SMOTE is possible and apply
  unique, counts = np.unique(y, return_counts=True)
  if np.all(counts > 1):
    x_balanced, y_balanced = smote.fit_resample(x_selected, y)
  else:
    x_balanced, y_balanced = x_selected, y

  # Feature Scaling (Z-score normalization)
  x_scaled = pd.DataFrame(scalar.fit_transform(x_balanced), columns=x_balanced.columns)

  # Return processed data and the fitted transformers for later use
  return x_scaled, y_balanced, scalar, imputer, selector


for i, (country_data) in enumerate(data):
    # Pass country_data.iloc[:-1] for training, as before
    x, y, scalar_fit, imputer_fit, selector_fit = prepare_xy_with_transformers(country_data.iloc[:-1])

