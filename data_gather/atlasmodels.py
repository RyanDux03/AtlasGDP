def prepare_future_data(models):

  all_country_predictions_dfs = []
  country_accuracies = []

  for i, (country_name, initial_country_data, x_train_original, x_test_original, y_train_original, y_test_original) in enumerate(test_train_data):
      scalar_fit, imputer_fit, selector_fit = fitted_transformers[i]
      model = models[i]

      # --- Step 1: Pre-process initial_country_data for consistent Label Encoding ---
      # Create a copy to avoid modifying the original DataFrame which might be used elsewhere
      processed_initial_country_data = initial_country_data.copy()

      # Identify categorical columns (excluding 'Year' and 'gdp_usd')
      categorical_cols = processed_initial_country_data.select_dtypes(include=['object']).columns.drop('Country', errors='ignore')

      # Store LabelEncoders for each categorical column for later use with future data
      country_label_encoders = {}
      for col in categorical_cols:
          le = LabelEncoder()
          # Fit and transform on the historical data
          processed_initial_country_data[col] = le.fit_transform(processed_initial_country_data[col])
          country_label_encoders[col] = le

      # Separate features (X) and target (Y) from the now label-encoded historical data
      x_historical_le = processed_initial_country_data.drop(columns=['Country', 'gdp_usd'])
      y_historical = processed_initial_country_data['gdp_usd']


      # --- Future Predictions (FIXED WITH TREND EXTRAPOLATION) ---
      last_year_in_historical_data = x_historical_le['Year'].max()
      future_years = [last_year_in_historical_data + j for j in range(1, 6)]

      # Prepare future feature rows using extrapolation based on original raw data first
      features_for_extrapolation = initial_country_data.drop(columns=['Country', 'gdp_usd']).copy()
      future_rows = []

      for future_year in future_years:
          future_row_dict = {}
          for col in features_for_extrapolation.columns:
              if col == 'Year':
                  future_row_dict[col] = future_year
              else:
                  if features_for_extrapolation[col].dtype in ['int64', 'float64']:
                      last_5_values = features_for_extrapolation[col].tail(5).values
                      if len(last_5_values) >= 2:
                          trend = last_5_values[-1] - last_5_values[0]
                          trend_per_year = trend / (len(last_5_values) - 1)
                          years_ahead = future_year - last_year_in_historical_data
                          future_row_dict[col] = last_5_values[-1] + (trend_per_year * years_ahead)
                      else:
                          future_row_dict[col] = features_for_extrapolation[col].iloc[-1]
                  else: # Categorical column
                      future_row_dict[col] = features_for_extrapolation[col].iloc[-1] # Use last known value as string

          future_rows.append(future_row_dict)

      x_future_raw = pd.DataFrame(future_rows)

      # Apply LabelEncoding to future data using the fitted encoders
      for col in categorical_cols:
          if col in x_future_raw.columns:
              # Use .loc for setting values to avoid SettingWithCopyWarning
              x_future_raw.loc[:, col] = country_label_encoders[col].transform(x_future_raw[col])

      # Apply Imputer, Selector, Scaler to future data
      x_future_imputed = pd.DataFrame(imputer_fit.transform(x_future_raw), columns=x_future_raw.columns)
      x_future_selected_np = selector_fit.transform(x_future_imputed)
      model_feature_names = x_train_original.columns # Feature names after selector during original training

      # Ensure that the columns of x_future_processed_df match model_feature_names in order and presence
      x_future_processed_df = pd.DataFrame(x_future_selected_np, columns=model_feature_names)
      x_future_scaled_np = scalar_fit.transform(x_future_processed_df) # Scale the selected features
      x_future_processed_df = pd.DataFrame(x_future_scaled_np, columns=model_feature_names)

      y_future = model.predict(x_future_processed_df)

      future_df = pd.DataFrame({
          "country": country_name,
          "year": future_years,
          "actual_gdp": np.nan,
          "predicted_gdp": y_future,
          "is_test": 0,
          "is_forecast": 1
      })

      # --- Create new time-based test_df and train_df ---
      all_years = x_historical_le['Year'].sort_values().unique()
      if len(all_years) >= 5:
          test_years_new = all_years[-5:]
          train_years_new = all_years[:-5]
      else: # If less than 5 years, treat all as test
          test_years_new = all_years
          train_years_new = []

      # Filter the label-encoded historical features (x_historical_le) and target (y_historical)
      x_test_new_le = x_historical_le[x_historical_le['Year'].isin(test_years_new)].copy()
      y_test_new_actual = y_historical[x_historical_le['Year'].isin(test_years_new)].copy()

      x_train_new_le = x_historical_le[x_historical_le['Year'].isin(train_years_new)].copy()
      y_train_new_actual = y_historical[x_historical_le['Year'].isin(train_years_new)].copy()

      # Apply Imputer, Selector, Scaler from `fitted_transformers`
      # Transform the new time-based test data
      x_test_new_imputed = pd.DataFrame(imputer_fit.transform(x_test_new_le), columns=x_test_new_le.columns)
      x_test_new_selected_np = selector_fit.transform(x_test_new_imputed)
      x_test_new_processed_df = pd.DataFrame(x_test_new_selected_np, columns=model_feature_names) # Use model's feature names
      x_test_new_scaled_np = scalar_fit.transform(x_test_new_processed_df) # Scale the selected features
      x_test_new_processed_df = pd.DataFrame(x_test_new_scaled_np, columns=model_feature_names)


      # Transform the new time-based train data (only if there is train data)
      if not x_train_new_le.empty:
          x_train_new_imputed = pd.DataFrame(imputer_fit.transform(x_train_new_le), columns=x_train_new_le.columns)
          x_train_new_selected_np = selector_fit.transform(x_train_new_imputed)
          x_train_new_processed_df = pd.DataFrame(x_train_new_selected_np, columns=model_feature_names) # Use model's feature names
          x_train_new_scaled_np = scalar_fit.transform(x_train_new_processed_df) # Scale the selected features
          x_train_new_processed_df = pd.DataFrame(x_train_new_scaled_np, columns=model_feature_names)
          y_train_new_pred = model.predict(x_train_new_processed_df)
      else:
          x_train_new_processed_df = pd.DataFrame(columns=model_feature_names) # Empty DataFrame
          y_train_new_pred = np.array([]) # Empty array


      # Make predictions using the already trained model
      y_test_new_pred = model.predict(x_test_new_processed_df)


      test_df = pd.DataFrame({
          "country": country_name,
          "year": test_years_new,
          "actual_gdp": np.nan,
          "predicted_gdp": y_test_new_pred,
          "is_test": 1,
          "is_forecast": 0
      })

      train_df = pd.DataFrame({
          "country": country_name,
          "year": train_years_new,
          "actual_gdp": y_train_new_actual.values if not y_train_new_actual.empty else np.array([]),
          "predicted_gdp": np.nan,
          "is_test": 0,
          "is_forecast": 0
      })

      # Concatenate all three dataframes for the current country
      country_combined_df = pd.concat([train_df, test_df, future_df], ignore_index=True)
      country_combined_df = country_combined_df.sort_values(by='year')
      all_country_predictions_dfs.append(country_combined_df)

      y_test_r2 = pd.concat([y_train_new_actual, y_test_new_actual])
      y_pred_r2 = np.concatenate([y_train_new_pred, y_test_new_pred])

      # Calculate R-squared
      r2_score_value = r2_score(y_test_r2, y_pred_r2)
      country_accuracies.append((country_name, r2_score_value))

      '''# plot predicted years
      plt.figure(figsize=(10, 6))
      plt.scatter(country_combined_df['year'], country_combined_df['predicted_gdp'], label='Future Predictions', color='blue')
      plt.xlabel('Year')
      plt.ylabel('Predicted GDP')
      plt.title(f'Predicted GDP for {country_name} Future Years')
      plt.legend()
      plt.grid(True)
      plt.show()'''

  final_all_country_predictions = pd.concat(all_country_predictions_dfs, ignore_index=True)
  return final_all_country_predictions, country_accuracies

df_rf_predictions, rf_country_accuracies = prepare_future_data(random_forest_models)
